func normalizeLang(s string) string {
	switch s {
	case "ja", "en", "fr", "de", "it", "es", "ru", "pt", "pl", "ko", "zh-Hans", "zh-Hant":
		return s
	}
	return "en"
}

func tr(lang, key string, args ...any) string {
	s, ok := msgs[normalizeLang(lang)][key]
	if !ok {
		s = msgs["en"][key]
	}
	if len(args) > 0 {
		return fmt.Sprintf(s, args...)
	}
	return s
}
